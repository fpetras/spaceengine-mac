#!/usr/bin/env python3
"""Generates the OpenGL bridge from the macOS OpenGL headers.

For every function Apple's core-profile headers declare, emits a thunk that
reads the arguments the way the game passed them (Windows x64 convention:
argument n in RCX/RDX/R8/R9 or XMM0-3 by position, the rest on the stack) and
calls the native function with its real prototype. The thunks are registered
by name, both for the game's direct OpenGL imports and for wglGetProcAddress.

usage: gen_gl.py <out.c>
"""
import re
import subprocess
import sys
from pathlib import Path

sdk = subprocess.run(["xcrun", "--show-sdk-path"], capture_output=True, text=True, check=True).stdout.strip()
headers = Path(sdk) / "System/Library/Frameworks/OpenGL.framework/Headers"
DECL = re.compile(r"^GLAPI\s+(.+?)\s+APIENTRY\s+(gl[A-Za-z0-9_]+)\s*\((.*?)\)", re.M)
FLOATS = {"GLfloat": "host_argf", "GLclampf": "host_argf", "GLdouble": "host_argd", "GLclampd": "host_argd"}
WIDE = {"GLint64", "GLuint64", "GLintptr", "GLsizeiptr", "GLsync", "GLuint64EXT", "GLint64EXT"}

functions = {}
for name in ("gl3.h", "gl3ext.h"):
    for ret, fn, params in DECL.findall((headers / name).read_text(errors="replace")):
        args = []
        for p in [a.strip() for a in params.split(",")]:
            if p in ("void", ""):
                continue
            # the type is everything up to the parameter name
            m = re.match(r"(.*?)(\w+)?(\s*\[\w*\])?$", p)
            typ = (m.group(1) or p).strip()
            if m.group(3) or not typ:      # array parameter, or an unnamed one
                typ = (typ or p).strip() + (" *" if m.group(3) else "")
            args.append(typ)
        functions.setdefault(fn, (ret.strip(), args))

out = ['// Generated by recomp/gen_gl.py from the macOS OpenGL headers. Do not edit.',
       '#define GL_SILENCE_DEPRECATION 1', '#include <OpenGL/gl3.h>', '#include <OpenGL/gl3ext.h>',
       '#include "host.h"', '#include "gl.h"', '']
for fn in sorted(functions):
    ret, args = functions[fn]
    call_args = []
    for i, typ in enumerate(args):
        if "*" in typ:
            call_args.append(f"({typ})host_arg(c, {i})")
        elif typ in FLOATS:
            call_args.append(f"{FLOATS[typ]}(c, {i})")
        else:
            call_args.append(f"({typ})host_arg(c, {i})")
    call = f"{fn}({', '.join(call_args)})"
    if ret == "void":
        body = f"{call};"
    elif "*" in ret or ret in WIDE:
        body = f"c->r[RAX] = (uint64_t){call};"
    elif ret == "GLboolean":
        body = f"c->r[RAX] = (uint8_t){call};"
    else:
        body = f"c->r[RAX] = (uint32_t){call};"
    unused = "" if args or ret != "void" else "(void)c; "
    check = "" if fn == "glGetError" else f' if (gl_check_errors) gl_report_error(c, "{fn}"); if (gl_logging) gl_log_call(c, "{fn}");'
    out.append(f"static void t_{fn}(cpu_t *c) {{ {unused}{body}{check} }}")
out.append("")
out.append("const gl_entry_t gl_native[] = {")
out += [f'    {{"{fn}", t_{fn}}},' for fn in sorted(functions)]
out.append("};")
out.append(f"const int gl_native_count = {len(functions)};")
Path(sys.argv[1]).write_text("\n".join(out) + "\n")
print(f"{len(functions)} OpenGL functions bridged from {headers}")
