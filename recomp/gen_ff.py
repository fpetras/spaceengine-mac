#!/usr/bin/env python3
"""Generates the FFmpeg bridge from the FFmpeg 8 headers.

The game loads avcodec-62.dll, avformat-62.dll, avutil-60.dll and
swscale-9.dll itself and looks up 297 functions by name
(analysis/ffmpeg_imports.tsv, found in the executable by tools/ffmpeg_names.py). For each, this emits a
thunk that reads the arguments the Windows way and calls the native function
with the prototype from FFmpeg's own headers, which clang reads here. The
native functions are found with dlsym when the game loads the libraries
(host/ffmpeg.c).

Handled by hand in host/ffmpeg.c instead (HAND below): functions that take a
file name, a callback or variable arguments.

usage: gen_ff.py <ffmpeg include dir> <out.c>
"""
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HAND = {"av_log_set_callback", "avcodec_default_execute", "avcodec_default_execute2", "avio_alloc_context",
        "avio_printf", "avformat_alloc_output_context2", "avio_open", "avio_open2", "avformat_open_input",
        "avio_check"}
SIGNED = {"int", "long", "long long", "short", "signed char", "char"}
SKIP = ("hwcontext_", "d3d", "vdpau", "dxva", "qsv", "vulkan", "mediacodec", "jni", "vaapi", "videotoolbox")


def main(include, out):
    include = Path(include)
    headers = [f"#include <{d}/{h.name}>" for d in ("libavcodec", "libavformat", "libavutil", "libswscale")
               for h in sorted((include / d).glob("*.h")) if not any(s in h.name for s in SKIP)]
    with tempfile.NamedTemporaryFile("w", suffix=".h", delete=False) as f:
        f.write("\n".join(headers) + "\n")
    ast = json.loads(subprocess.run(["clang", "-fsyntax-only", f"-I{include}", "-x", "c", "-Xclang", "-ast-dump=json", f.name],
                                    capture_output=True, text=True, check=True).stdout)
    wanted = [line.split("\t") for line in (ROOT / "analysis/ffmpeg_imports.tsv").read_text().splitlines()[1:] if line]
    decls = {}
    for n in ast["inner"]:
        if n.get("kind") == "FunctionDecl" and n.get("name") not in decls:
            params = [(p["type"]["qualType"], p["type"].get("desugaredQualType", p["type"]["qualType"]))
                      for p in n.get("inner", []) if p.get("kind") == "ParmVarDecl"]
            ret = n["type"]["qualType"].split("(")[0].strip()
            decls[n["name"]] = (ret, params, n.get("variadic", False))

    lines = ["// Generated by recomp/gen_ff.py from the FFmpeg 8 headers. Do not edit."]
    lines += [h for h in headers] + ['#include <string.h>', '#include "host.h"', '#include "gl.h"', '#include "ffmpeg.h"', ""]
    lines += ["static AVRational rational(uint64_t v) { AVRational r; memcpy(&r, &v, 8); return r; }",
              "static uint64_t from_rational(AVRational r) { uint64_t v; memcpy(&v, &r, 8); return v; }", ""]
    table = []
    for library, name in wanted:
        if name in HAND:
            table.append(f'    {{"{library}", "{name}", NULL, NULL}},')
            continue
        ret, params, variadic = decls[name]
        assert not variadic, name
        args = []
        for i, (typ, plain) in enumerate(params):
            if plain == "double":
                args.append(f"host_argd(c, {i})")
            elif plain == "float":
                args.append(f"host_argf(c, {i})")
            elif typ == "AVRational" or plain in ("AVRational", "struct AVRational"):
                args.append(f"rational(host_arg(c, {i}))")
            elif name == "av_strerror" and i == 0:
                args.append("ff_error_from_windows((int)host_arg(c, 0))")
            else:
                assert "(*)" not in plain and not (plain.startswith("struct ") and "*" not in plain), (name, typ)
                args.append(f"({typ})host_arg(c, {i})")
        call = f"p_{name}({', '.join(args)})"
        rplain = ret
        if ret == "void":
            body = f"{call};"
        elif ret in ("double", "float"):
            body = f"c->x[0].f64[0] = 0; c->x[0].{'f64' if ret == 'double' else 'f32'}[0] = {call};"
        elif ret == "AVRational":
            body = f"c->r[RAX] = from_rational({call});"
        elif ret == "int":
            # Negative results are AVERROR codes; those made from errno values differ between the systems.
            body = f"c->r[RAX] = (uint64_t)(int64_t)ff_error_to_windows({call});"
        elif rplain in SIGNED or rplain.startswith("enum ") or rplain.startswith("int"):
            body = f"c->r[RAX] = (uint64_t)(int64_t){call};"
        else:
            body = f"c->r[RAX] = (uint64_t){call};"
        lines.append(f"static __typeof__({name}) *p_{name};")
        lines.append(f"static void t_{name}(cpu_t *c) {{ {body} }}")
        table.append(f'    {{"{library}", "{name}", (void **)&p_{name}, t_{name}}},')
    lines += ["", "const ff_entry_t ff_functions[] = {"] + table + ["};",
              "const int ff_function_count = sizeof ff_functions / sizeof ff_functions[0];"]
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"{out}: {len(table)} functions, {sum(1 for _, n in wanted if n in HAND)} by hand")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
